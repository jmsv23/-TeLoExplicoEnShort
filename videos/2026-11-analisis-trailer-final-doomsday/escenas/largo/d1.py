"""DETALLE 1 · Steve se quedó… y tuvo un hijo."""
from esc_largo._k import tag, tv, clipsc, still


def build(S):
    s = S.scene(S.w("Detalle uno"), bg="papel", enter="halftone")
    tv(s, "casa", 1.3, s.start + 0.02, S.peek("Abre en una casa") - s.start + 0.3, slam=False)
    t = S.w("no abre en Latveria")
    s.sello("nol", "NO ABRE EN LATVERIA", 1380, 860, t, color="rojo", rot=-6, size=60)
    s = S.scene(S.w("Abre en una casa"), bg="tinta", enter="cut")
    tv(s, "sp", 4.0, s.start, S.peek("Durante meses") - s.start, slam=False)
    tag(s, "C", s.start + 0.2)
    t = S.w("barba")
    s.text("bb", "¡BARBA!", "ono", "amarillo", 1550, 860, t, rot=-6)

    s = S.scene(S.w("Durante meses"), bg="ceniza", enter="whip")
    still(s, "sb", "steve-barba", (110, 70, 1700, 940), s.start + 0.02, kb=S.peek("No."), pos="50% 30%")
    t = S.w("algo malo")
    s.globo("g1", "¿ESCONDIDO? ¿DERROTADO?", 120, 760, 760, 200, t, size=54, rot=-3)
    t = S.w("No.")
    s = S.scene(t, bg="papel", enter="pageflip")
    t = S.w("pasaron los años")
    still(s, "b1", "bebe", (60, 120, 580, 400), t - 0.2, frm="L", label="0 AÑOS")
    still(s, "b2", "bici", (670, 120, 580, 400), t + 0.6, frm="B", label="5 AÑOS")
    still(s, "b3", "hijo", (1280, 120, 580, 400), t + 1.4, frm="R", label="¿15 AÑOS?", pos="50% 30%")
    t = S.w("Peggy")
    s.text("pg", "STEVE + PEGGY", "kw", "rojo", 960, 680, t, size=96, rot=-3)
    t = S.w("tuvieron un hijo")
    s.text("hj", "…Y UN HIJO", "ttl", "amarillo", 960, 880, t, size=130, rot=-4, misreg=True)

    s = S.scene(S.w("Y ese hijo"), bg="tinta", enter="ink")
    tv(s, "corre", 26.6, s.start + 0.02, S.peek("Steve guardó") - s.start, slam=False)
    t = S.w("no sabe")
    s.text("ns", "NO SABE NADA", "kw", "amarillo", 960, 940, t, size=90, rot=-3)
    s = S.scene(S.w("Steve guardó"), bg="tinta", enter="cut")
    still(s, "baul", "baul", (110, 70, 1700, 940), s.start + 0.02, kb=S.clip(0)["start"], scale=1.2)
    t = S.w("baúl")
    s.text("ba", "EL TRAJE, EN UN BAÚL", "kw", "papel", 960, 140, t, size=80, rot=-3)

    clipsc(S, 0)

    s = S.scene(S.w("Dato de cómic"), bg="doom", enter="ink", color="doom")
    tag(s, "K", s.start + 0.1)
    still(s, "sil", "hijo", (80, 160, 760, 820), s.start + 0.2, kb=S.peek("La pregunta"), frm="L", pos="50% 30%", label="¿EL JAMES ROGERS DEL MCU?")
    t = S.w("James Rogers")
    s.text("jr", "JAMES ROGERS", "ttl", "amarillo", 1260, 380, t, size=130, rot=-4)
    t = S.w("Next Ávengers")
    s.text("na", "NEXT AVENGERS (2008)", "kw", "papel", 1260, 560, t, size=70, rot=-2)
    t = S.w("Viuda Negra")
    s.globo("vn", "HIJO DE STEVE Y LA VIUDA NEGRA", 900, 700, 860, 170, t, size=46, rot=2)
    t = S.w("la madre es Peggy")
    s.text("op", "AQUÍ: PEGGY", "ono", "rojo", 1300, 960, t, rot=-6)

    s = S.scene(S.w("La pregunta"), bg="multi", enter="halftone", color="multi")
    tag(s, "T", S.peek("suero"))
    still(s, "hj", "hijo", (110, 70, 1000, 940), s.start + 0.05, kb=S.t1, frm="L", pos="50% 30%")
    t = S.w("suero")
    s.text("su", "¿EL SUERO?", "ttl", "amarillo", 1480, 360, t, size=140, rot=-5, misreg=True)
    t = S.w("no lo dice")
    s.text("nd", "NO LO DICE", "kw", "papel", 1480, 600, t, size=80, rot=-3)
    t = S.w("leyenda")
    s.text("le", "¡SU PAPÁ ERA UNA LEYENDA!", "kw", "amarillo", 1400, 880, t, size=58, rot=-2)
